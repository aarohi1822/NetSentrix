"""Merge benchmark outputs into results/metrics.json and render the README results table.

Usage (after running src/benchmark_smap.py for each spacecraft):

    python src/collect_results.py --input-dir data/processed/evaluation --update-readme

The README section between RESULTS_START and RESULTS_END is regenerated from
results/metrics.json only, so the published table always matches the saved file.
"""
from __future__ import annotations

import argparse
import json
import math
import subprocess
from pathlib import Path
from typing import Any

import pandas as pd

RESULTS_START = "<!-- RESULTS:START (generated by src/collect_results.py from results/metrics.json; do not edit) -->"
RESULTS_END = "<!-- RESULTS:END -->"

DETECTORS = (
    ("lstm_autoencoder", "LSTM-AE"),
    ("isolation_forest", "Isolation Forest"),
    ("first_difference", "\\|x<sub>t</sub> − x<sub>t−1</sub>\\| baseline"),
)
ANOMALY_TYPES = (("spike", "Spike"), ("level_shift", "Level shift"), ("drift", "Gradual drift"))
CONFIG_KEYS = (
    "window_size",
    "epochs",
    "batch_size",
    "latent_dim",
    "threshold_method",
    "percentile",
    "k",
    "smoothing_window",
    "diff_columns",
    "seed",
)


def _clean(value: Any) -> Any:
    """Replace NaN/inf with None so the output is strict JSON."""
    if isinstance(value, float) and not math.isfinite(value):
        return None
    if isinstance(value, dict):
        return {k: _clean(v) for k, v in value.items()}
    if isinstance(value, list):
        return [_clean(v) for v in value]
    return value


def _git_commit() -> str | None:
    try:
        commit = subprocess.run(
            ["git", "rev-parse", "HEAD"], capture_output=True, text=True, check=True
        ).stdout.strip()
        dirty = subprocess.run(
            ["git", "status", "--porcelain", "--", "src"], capture_output=True, text=True, check=True
        ).stdout.strip()
        return f"{commit}{'-dirty' if dirty else ''}"
    except (OSError, subprocess.CalledProcessError):
        return None


def load_dataset_results(input_dir: Path, spacecraft: str) -> dict:
    stem = spacecraft.lower()
    summary = json.loads((input_dir / f"{stem}_benchmark_summary.json").read_text(encoding="utf-8"))
    channels = pd.read_csv(input_dir / f"{stem}_channel_metrics.csv")
    attribution_path = input_dir / f"{stem}_attribution_injections.csv"
    injections = pd.read_csv(attribution_path) if attribution_path.stat().st_size > 1 else pd.DataFrame()

    detectors = {}
    for key, _ in DETECTORS:
        block = dict(summary[key])
        channel_mean = block.pop("channel_mean")
        detectors[key] = {"pooled": block, "channel_mean": channel_mean}

    config = {k: summary[k] for k in CONFIG_KEYS if k in summary}
    command = (
        f"python src/benchmark_smap.py --spacecraft {spacecraft} --epochs {config['epochs']} "
        f"--batch-size {config['batch_size']} --window-size {config['window_size']} "
        f"--latent-dim {config['latent_dim']} --threshold-method {config['threshold_method']} "
        f"--percentile {config['percentile']} --k {config['k']} "
        f"--smoothing-window {config['smoothing_window']} --seed {config['seed']} "
        f"--n-injections {summary['attribution']['n_injections']} --diff-columns {config['diff_columns']}"
    )
    return {
        "channel_count": summary["channel_count"],
        "config": config,
        "command": command,
        "runtime_seconds": summary["runtime_seconds"],
        "detectors": detectors,
        "attribution": summary["attribution"],
        "channels": channels.to_dict(orient="records"),
        "injections": injections.to_dict(orient="records"),
    }


def collect(input_dir: Path, spacecrafts: list[str]) -> dict:
    return _clean(
        {
            "generated_by": "src/collect_results.py",
            "source_dir": str(input_dir),
            "git_commit": _git_commit(),
            "metric_definitions": {
                "strict": "point-wise precision/recall/F1 over every test timestep",
                "adjusted": "point-adjusted: an event counts as fully detected if any timestep in it is flagged; "
                "applied per channel before pooling",
                "channel_mean": "unweighted mean of per-channel metrics (NaN channels ignored)",
                "pooled": "recomputed from confusion counts summed over all channels",
                "mean_latency": "timesteps from event start to first alert inside the event, over detected events",
                "false_alarms_per_1k": "alert runs not overlapping any labelled event, per 1,000 test timesteps",
                "attribution_hit": "injected column ranks top-k by per-feature reconstruction MSE averaged over "
                "windows containing the injection; chance = expected rate under a random ranking",
            },
            "datasets": {sc: load_dataset_results(input_dir, sc) for sc in spacecrafts},
        }
    )


def _f(value: Any, digits: int = 3) -> str:
    return "n/a" if value is None else f"{value:.{digits}f}"


def render_results_markdown(results: dict) -> str:
    datasets = results["datasets"]
    lines = [
        "Generated from [`results/metrics.json`](results/metrics.json). "
        "All detectors use the same per-channel test split and the same threshold rule "
        "(percentile / mean+k·std of smoothed *training* scores). "
        "**ch-mean** = unweighted mean over channels; **pooled** = recomputed over all test points "
        "(point adjustment applied per channel first).",
        "",
        "| Dataset | Model | Strict F1 (ch-mean / pooled) | Point-adj F1 (ch-mean / pooled) "
        "| Pooled precision / recall | ROC-AUC (ch-mean) | Events detected | Mean latency (steps) "
        "| False alarms / 1k pts |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for name, data in datasets.items():
        for key, label in DETECTORS:
            pooled = data["detectors"][key]["pooled"]
            mean = data["detectors"][key]["channel_mean"]
            lines.append(
                f"| {name} ({data['channel_count']} ch) | {label} "
                f"| {_f(mean['f1'])} / {_f(pooled['f1'])} "
                f"| {_f(mean['adjusted_f1'])} / {_f(pooled['adjusted_f1'])} "
                f"| {_f(pooled['precision'])} / {_f(pooled['recall'])} "
                f"| {_f(mean['roc_auc'])} "
                f"| {pooled['detected_events']}/{pooled['events']} "
                f"| {_f(pooled['mean_latency'], 1)} "
                f"| {_f(pooled['false_alarms_per_1k'], 2)} |"
            )

    header = "| Anomaly type |" + "".join(
        f" {name} top-1 / top-3 (n) |" for name in datasets
    )
    lines += [
        "",
        "**Root-cause attribution** — synthetic anomalies injected into random input columns and timesteps "
        "of the test data; a hit means the injected column ranks top-k by per-feature reconstruction error. "
        "Chance is the expected hit rate of a random ranking.",
        "",
        header,
        "|---|" + "---|" * len(datasets),
    ]
    for key, label in (*ANOMALY_TYPES, ("overall", "All")):
        cells = []
        for data in datasets.values():
            block = data["attribution"]["by_type"].get(key, {})
            cells.append(
                f"{_f(block.get('top1_hit_rate'), 2)} / {_f(block.get('top3_hit_rate'), 2)} ({block.get('n', 0)})"
                if block.get("n")
                else "n/a"
            )
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    chance_cells = []
    for data in datasets.values():
        overall = data["attribution"]["by_type"]["overall"]
        chance_cells.append(f"{_f(overall.get('top1_chance'), 2)} / {_f(overall.get('top3_chance'), 2)}")
    lines.append("| Random chance | " + " | ".join(chance_cells) + " |")

    lines += ["", "Reproduce (seeded, deterministic TF ops):", "", "```bash"]
    lines += [data["command"] for data in datasets.values()]
    lines += [
        f"python src/collect_results.py --input-dir {results['source_dir']} --update-readme",
        "```",
    ]
    return "\n".join(lines)


def update_readme(readme_path: Path, block: str) -> None:
    text = readme_path.read_text(encoding="utf-8")
    if RESULTS_START not in text or RESULTS_END not in text:
        raise ValueError(f"{readme_path} has no results markers; add {RESULTS_START!r} and {RESULTS_END!r}.")
    before, rest = text.split(RESULTS_START, 1)
    _, after = rest.split(RESULTS_END, 1)
    readme_path.write_text(f"{before}{RESULTS_START}\n{block}\n{RESULTS_END}{after}", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--input-dir", default="data/processed/evaluation")
    parser.add_argument("--spacecraft", nargs="+", default=["SMAP", "MSL"])
    parser.add_argument("--output", default="results/metrics.json")
    parser.add_argument("--readme", default="README.md")
    parser.add_argument("--update-readme", action="store_true")
    args = parser.parse_args()

    results = collect(Path(args.input_dir), args.spacecraft)
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(results, indent=2, allow_nan=False), encoding="utf-8")
    print(f"Saved {output}")

    if args.update_readme:
        # Render from the saved file, not the in-memory object, so README == metrics.json.
        saved = json.loads(output.read_text(encoding="utf-8"))
        update_readme(Path(args.readme), render_results_markdown(saved))
        print(f"Updated results table in {args.readme}")


if __name__ == "__main__":
    main()
